const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const tabs = await fetch('http://localhost:9222/json').then(r => r.json());
  const tab = tabs.find(t => t.type === 'page' && t.url.includes(':8000'));
  const ws = new WebSocket(tab.webSocketDebuggerUrl);
  await new Promise(resolve => ws.addEventListener('open', resolve, { once: true }));
  let id = 0; const pending = new Map();
  ws.onmessage = e => { const msg = JSON.parse(e.data); if (msg.id) { pending.get(msg.id)?.(msg); pending.delete(msg.id); } };
  const send = (method, params = {}) => new Promise(resolve => { const key = ++id; pending.set(key, resolve); ws.send(JSON.stringify({ id: key, method, params })); });
  const evaluate = async expression => { const r = await send('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true }); if (r.result?.exceptionDetails) throw Error(JSON.stringify(r.result.exceptionDetails)); return r.result.result.value; };
  const wait = ms => new Promise(r => setTimeout(r, ms));
  const capture = async name => { const r = await send('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync(`artifacts/${name}.png`, Buffer.from(r.result.data, 'base64')); };
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  fs.mkdirSync('artifacts', { recursive: true });
  await capture('mission-before');
  await send('Page.reload', { ignoreCache: true });
  for (let i = 0; i < 90; i++) { if (await evaluate(`document.querySelector('#loading-overlay')?.classList.contains('is-hidden')`)) break; await wait(1000); }
  console.log(await evaluate(`(async () => {
    const m = await import('./mission-board.js');
    const a = await import('./app.js'); const c = await import('./checker/checker.js');
    a.installCheck(await c.checkAccount('city@demo.test'));
    window.missionSnapshot = JSON.stringify(a.accounts);
    a.showMissionBoard();
    return { missions: m.buildMissions(a.accounts).length, links: document.querySelectorAll('.mission-actions a').length, gcpdLoaded: a.landmarkRoots.some(r => r.userData.landmark === 'GCPD Headquarters') };
  })()`));
  await wait(3000);
  assert.ok(await evaluate(`document.querySelectorAll('.mission-card').length > 0`));
  assert.ok(await evaluate(`[...document.querySelectorAll('.mission-actions a')].every(a => a.protocol === 'https:' && a.target === '_blank' && a.rel.includes('noopener'))`));
  await capture('gcpd-missions');
  await evaluate(`document.querySelector('.mission-complete').click()`);
  assert.ok(await evaluate(`document.querySelector('.mission-announcement').textContent.includes('marked complete')`));
  assert.equal(await evaluate(`(async () => JSON.stringify((await import('./app.js')).accounts) === window.missionSnapshot)()`), true);
  await evaluate(`document.querySelector('[data-filter="done"]').click()`);
  assert.ok(await evaluate(`document.querySelector('.mission-card.is-complete') !== null`));
  await capture('gcpd-completed');
  await send('Page.reload', { ignoreCache: true });
  await wait(3000);
  await evaluate(`(async () => { const a = await import('./app.js'); const c = await import('./checker/checker.js'); a.installCheck(await c.checkAccount('city@demo.test')); a.showMissionBoard(); document.querySelector('[data-filter="done"]').click(); })()`);
  assert.ok(await evaluate(`document.querySelector('.mission-card.is-complete') !== null`), 'Completion persists after reload');
  await evaluate(`document.querySelector('.mission-complete').click()`);
  assert.ok(await evaluate(`document.querySelector('.mission-announcement').textContent.includes('reopened')`));
  await evaluate(`(async () => { const a = await import('./app.js'); const c = await import('./checker/checker.js'); a.installCheck(await c.checkAccount('clear@demo.test')); a.showMissionBoard(); })()`);
  assert.ok(await evaluate(`document.querySelector('.mission-empty') !== null`));
  await evaluate(`(async () => { const a = await import('./app.js'); const c = await import('./checker/checker.js'); a.installCheck(await c.checkAccount('city@demo.test')); a.showMissionBoard(); document.querySelector('[data-filter="open"]').click(); })()`);
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await wait(1500);
  assert.ok(await evaluate(`(() => { const r = document.querySelector('.is-mission-board').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight; })()`), 'Board fits mobile viewport');
  await capture('gcpd-mobile');
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await evaluate(`import('./app.js').then(a => a.showMissionBoard())`);
  console.log('PASS: task generation, links, completion, undo, persistence, unchanged breach records, clear empty state, mobile fit.');
  ws.close();
})().catch(e => { console.error(e); process.exit(1); });
